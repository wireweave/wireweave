import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { fileURLToPath, URL } from 'node:url'

import ts from 'typescript'
import { formatGeneratedSource } from './format-generated.mjs'

const require = createRequire(import.meta.url)
/** @type {unknown} */
const esbuild = createRequire(require.resolve('tsup'))('esbuild')
const { transform } =
  /** @type {{transform: (source: string, options: Record<string, unknown>) => Promise<{code: string}>}} */ (
    esbuild
  )
const directory = new URL('../src/app/', import.meta.url)
const output = fileURLToPath(new URL('native-runtime.generated.ts', directory))

/** @param {string} file @param {string} name */
function declaration(file, name) {
  const text = readFileSync(new URL(file, directory), 'utf8')
  const source = ts.createSourceFile(file, text, ts.ScriptTarget.ESNext, true)
  const matches = source.statements.filter(
    (statement) => ts.isFunctionDeclaration(statement) && statement.name?.text === name,
  )
  const [node] = matches
  if (matches.length !== 1 || !ts.isFunctionDeclaration(node) || !node.body) {
    throw new Error(`Expected one runtime function implementation: ${name}`)
  }
  const local = ts.factory.updateFunctionDeclaration(
    node,
    undefined,
    node.asteriskToken,
    node.name,
    node.typeParameters,
    node.parameters,
    node.type,
    node.body,
  )
  return ts.createPrinter().printNode(ts.EmitHint.Unspecified, local, source)
}

const source = `(() => {
  ${declaration('compiler.ts', 'runtimeEngine')}
  ${declaration('browser-adapter.ts', 'browserAdapter')}
  const program = JSON.parse(document.getElementById("wf-runtime-data").textContent);
  browserAdapter(runtimeEngine(program), program);
})();`
const { code } = await transform(source, {
  loader: 'ts',
  target: 'es2019',
  minifyWhitespace: true,
  legalComments: 'none',
  charset: 'ascii',
})
const runtime = code.trimEnd()
if (/<\/script/iu.test(runtime)) throw new Error('Inline runtime contains a script end tag')
const generated = await formatGeneratedSource(
  `// Generated by scripts/generate-native-runtime.mjs. Do not edit.\nexport const NATIVE_RUNTIME = ${JSON.stringify(runtime)}\n`,
  output,
)

if (process.argv.includes('--check')) {
  if (!existsSync(output) || readFileSync(output, 'utf8') !== generated) {
    throw new Error(
      'Native runtime is stale. Run pnpm --filter @wireweave/core build:native-runtime.',
    )
  }
} else {
  writeFileSync(output, generated)
}
